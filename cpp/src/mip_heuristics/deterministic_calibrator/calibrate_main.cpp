void run_single_hinge(const std::string& algo,
                      const std::vector<std::string>& base_names,
                      std::vector<calibration_sample_t> samples,
                      std::string out_header)
{
  if (samples.size() < 2) {
    std::printf("Not enough samples (%zu)\n", samples.size());
    return;
  }
  auto names                 = base_names;
  const std::size_t hinge_on = names.size() - 1;  // last feature (total warp loads)
  names.push_back("excess_warp_loads");

  auto augment = [&](std::vector<calibration_sample_t> s, double T) {
    for (auto& x : s) {
      x.features.push_back(std::max(0.0, x.features[hinge_on] - T));
    }
    return s;
  };

  work_calibrator_t cal;
  const std::vector<double> Ts = {0, 2000, 4000, 8000, 16000, 32000, 64000, 128000, 256000};
  double best_cv               = 1e30;
  double best_T                = 0.0;
  calibration_result_t best_fit;
  std::vector<calibration_sample_t> best_samples;
  for (double T : Ts) {
    auto sT  = augment(samples, T);
    auto fit = cal.fit(sT, names.size(), work_calibrator_t::options_t{});
    std::printf("  [grid] T=%.0f -> CV=%.4f\n", T, fit.cv);
    if (fit.cv < best_cv) {
      best_cv      = fit.cv;
      best_T       = T;
      best_fit     = fit;
      best_samples = std::move(sT);
    }
  }
  std::printf("\n=== %s fit ===\nsamples=%zu best T=%.0f CV=%.4f\n",
              algo.c_str(),
              best_samples.size(),
              best_T,
              best_cv);
  for (std::size_t i = 0; i < best_fit.coeffs.size(); ++i) {
    std::printf("  [%s] = %.6g\n", names[i].c_str(), best_fit.coeffs[i]);
  }
  std::printf("\nper-instance ratio (measured/predicted):\n");
  for (const auto& s : best_samples) {
    const double pred = predict_work(best_fit.coeffs, s.features);
    std::printf("  %-28s meas=%.3e pred=%.3e ratio=%.3f\n",
                s.instance.c_str(),
                s.measured_time_per_iter,
                pred,
                s.measured_time_per_iter / pred);
  }
  if (out_header.empty()) {
    out_header =
      "cpp/src/mip_heuristics/deterministic_calibrator/generated/" + algo + "_work_coeffs.hpp";
  }
  emit_single_hinge_header(out_header, algo, names, best_fit, best_T);
  std::printf("\nWrote %s\n", out_header.c_str());
}


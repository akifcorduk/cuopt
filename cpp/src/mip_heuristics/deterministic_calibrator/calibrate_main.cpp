// ---- FJ: single linear model ----
void run_fj(const std::string& dataset_dir, std::string out_header)
{
  std::vector<calibration_sample_t> samples;
  for (const auto& name : kInstances) {
    const std::string path = dataset_dir + "/" + name + ".mps";
    std::printf("\n[instance] %s\n", name.c_str());
    std::fflush(stdout);
    try {
      samples.push_back(run_fj_calibration_sample(path, name));
    } catch (const std::exception& e) {
      std::printf("  SKIP (%s)\n", e.what());
    }
  }
  if (samples.size() < 2) {
    std::printf("Not enough samples (%zu)\n", samples.size());
    return;
  }
  const auto names = fj_feature_names();
  work_calibrator_t cal;
  auto result = cal.fit(samples, names.size(), work_calibrator_t::options_t{});
  std::printf("\n=== fj fit ===\nsamples=%zu CV=%.4f converged=%s\n",
              samples.size(),
              result.cv,
              result.converged ? "yes" : "no");
  for (std::size_t i = 0; i < result.coeffs.size(); ++i) {
    std::printf("  coeff[%s] = %.6g\n", names[i].c_str(), result.coeffs[i]);
  }
  if (out_header.empty()) {
    out_header = "cpp/src/mip_heuristics/deterministic_calibrator/generated/fj_work_coeffs.hpp";
  }
  emit_coeffs_header(out_header, "fj", names, result, samples);
  std::printf("Wrote %s\n", out_header.c_str());
}

// ---- BP: per-kernel models (activity + bounds-update), summed at runtime ----

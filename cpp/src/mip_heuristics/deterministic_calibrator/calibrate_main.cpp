  f << " * SPDX-License-Identifier: Apache-2.0\n *\n";
  f << " * AUTO-GENERATED by mip_work_calibrator. Do not edit by hand.\n";
  f << " * Algorithm: " << algo << " (per-kernel: activity + bounds-update)\n";
  f << " * Combined per-iteration CV (measured/predicted): " << combined_cv << "\n";
  f << " * activity sub-fit CV: " << act.cv << "   bounds-update sub-fit CV: " << upd.cv << "\n";
